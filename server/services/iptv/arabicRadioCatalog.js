function buildRadioSources(directUrl, stationKey, backupUrl) {
  const sources = [
    {
      id: `${stationKey}-srv-1`,
      name: 'بث الراديو المباشر (Direct Stream)',
      url: directUrl,
      qualityHint: 'HQ Audio Live',
    },
    {
      id: `${stationKey}-srv-2`,
      name: 'سيرفر البروكسي المحلي (ARN Proxy)',
      url: directUrl.includes('.m3u8')
        ? `/api/live/proxy/m3u8?u=${encodeURIComponent(directUrl)}`
        : `/api/live/proxy/audio?u=${encodeURIComponent(directUrl)}`,
      isProxied: true,
      qualityHint: 'Local Proxy · CORS Bypass',
    },
  ];
  if (backupUrl) {
    sources.push(
      {
        id: `${stationKey}-srv-3`,
        name: 'سيرفر البث الاحتياطي (Backup Stream)',
        url: backupUrl,
        qualityHint: 'Secondary Direct',
      },
      {
        id: `${stationKey}-srv-4`,
        name: 'بروكسي السيرفر الاحتياطي (ARN Backup Proxy)',
        url: backupUrl.includes('.m3u8')
          ? `/api/live/proxy/m3u8?u=${encodeURIComponent(backupUrl)}`
          : `/api/live/proxy/audio?u=${encodeURIComponent(backupUrl)}`,
        isProxied: true,
        qualityHint: 'Secondary Proxy',
      }
    );
  }
  return sources;
}

